"""Split the two twenty-column supplementary tables into readable parts.

The external review asked for the wide supplementary tables to be broken into
grouped, readable pieces rather than one `\\resizebox`-ed slab per topic.  This
script does that as a *mechanical re-grouping* of the frozen artifacts: every
number is copied verbatim out of the frozen source and re-emitted, and the
script then asserts that the multiset of numeric tokens in its outputs is
exactly the multiset in the frozen sources.  Nothing is retyped, rounded or
recomputed.

Inputs (frozen):
  tables/supplementary_systematics_14bin.tex       -> S2 (detector)   + S3 (modelling/scale)
  tables/supplementary_conformal_round1.tex        -> S4 (coverage)   + S5 (set structure)
  data/tables/shap_delta_per_feature.csv           -> S6 (per feature) + S7 (score/rank)

The SHAP outputs are cross-checked against the frozen twenty-column
`supplementary_shap_delta_round3_all_features.tex` as an independent second
source for the same values.
"""

from __future__ import annotations

import csv
import re
from collections import Counter
from pathlib import Path

import os

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parent.parent            # the ATLAS 80030 project root
# Frozen campaign outputs: "04_Results" in the current layout (also the public
# repository), "Code files/analysis_results" in the original project layout.
_RESULTS = next((r for r in (PROJECT / "04_Results",
                             PROJECT / "Code files" / "analysis_results") if r.is_dir()),
                PROJECT / "04_Results")
_FROZEN = _RESULTS / "shap_delta_final_production_round3"
DATA = Path(os.environ["ATLAS80030_SHAP_DIR"]) if "ATLAS80030_SHAP_DIR" in os.environ \
    else (_FROZEN if _FROZEN.is_dir() else HERE.parent / "data" / "tables")

NUM = re.compile(r"-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?")


def body_rows(path: Path) -> list[list[str]]:
    """Every data row of a booktabs table, as a list of stripped cells."""
    text = path.read_text(encoding="utf-8")
    inside = False
    rows: list[list[str]] = []
    for raw in text.splitlines():
        line = raw.strip()
        if line == r"\midrule":
            inside = True
            continue
        if line in (r"\bottomrule", r"\end{longtable}"):
            inside = False
            continue
        if not inside or not line.endswith(r"\\") or line.startswith("%"):
            continue
        cells = [c.strip() for c in line[:-2].split("&")]
        rows.append(cells)
    return rows


def tokens(text: str) -> Counter:
    return Counter(NUM.findall(text))


def emit(path: Path, caption: str, label: str, colspec: str,
         header: list[str], rows: list[list[str]], *,
         landscape: bool = False, star: bool = True,
         size: str = "small", tabcolsep: str | None = None,
         note: str | None = None) -> str:
    env = "table*" if star else "table"
    out = ["% Generated by tables/make_supplementary_tables.py from the frozen",
           "% artifacts. Every value is copied verbatim; see PROVENANCE.md.",
           "% Requires \\usepackage{booktabs}" +
           (", pdflscape." if landscape else ".")]
    if landscape:
        out.append(r"\begin{landscape}")
    out += [f"\\begin{{{env}}}[{'p' if landscape else '!ht'}]", r"\centering", "\\" + size]
    if tabcolsep:
        out.append(r"\setlength{\tabcolsep}{" + tabcolsep + "}")
    out += [
            f"\\caption{{{caption}}}", f"\\label{{{label}}}",
            f"\\begin{{tabular}}{{{colspec}}}", r"\toprule",
            " & ".join(header) + r" \\", r"\midrule"]
    out += [" & ".join(r) + r" \\" for r in rows]
    out += [r"\bottomrule", r"\end{tabular}"]
    if note:
        out.append(r"\par\vspace{4pt}")
        out.append(r"\begin{minipage}{\textwidth}\footnotesize " + note +
                   r"\end{minipage}")
    out.append(f"\\end{{{env}}}")
    if landscape:
        out.append(r"\end{landscape}")
    text = "\n".join(out) + "\n"
    path.write_text(text, encoding="utf-8")
    return text


# ------------------------------------------------------------ systematics ---
def systematics() -> None:
    src = HERE / "supplementary_systematics_14bin.tex"
    rows = body_rows(src)
    assert len(rows) == 14 and all(len(r) == 20 for r in rows), (
        len(rows), {len(r) for r in rows})

    # 0 pt_low 1 pt_high 2 nominal BR 3 CES 4 CER 5 CPOS 6 cluster total
    # 7 track eff 8 fake 9 bias 10 track total 11 sig model 12 bkg model
    # 13 model total 14 sig ISR 15 sig FSR 16 bkg ISR 17 bkg FSR
    # 18 ISR/FSR total 19 total
    det = [[r[0], r[1], r[2], r[3], r[4], r[5], r[6], r[7], r[8], r[9], r[10]]
           for r in rows]
    mod = [[r[0], r[1], r[11], r[12], r[13], r[14], r[15], r[16], r[17],
            r[18], r[19]] for r in rows]

    a = emit(
        HERE / "supp_s2_systematics_detector.tex",
        "Detector systematic uncertainties on background rejection at $50\\%$ "
        "signal efficiency, in each of the fourteen physical $200$~GeV $\\pt$ "
        "bins. All uncertainty columns are relative uncertainties in percent. "
        "The nominal background rejection is repeated here so that each "
        "relative uncertainty can be read against the value it applies to.",
        "tab:supp-syst-detector",
        "rrr rrrr rrrr",
        [r"$\pt$ low", r"$\pt$ high", "Nominal BR",
         "CES", "CER", "CPOS", "Cluster total",
         "Track eff.", "Fake rate", "Bias", "Track total"],
        det,
        note=r"$\pt$ bin edges in GeV. CES is the \texttt{esup}/\texttt{esdown} "
             r"envelope, track efficiency the \texttt{teg}/\texttt{tej} "
             r"envelope and fake rate the \texttt{tfl}/\texttt{tfj} envelope; "
             r"category totals are quadrature sums of the components to their "
             r"left.",
        landscape=True, star=False, size="footnotesize", tabcolsep="4pt")
    b = emit(
        HERE / "supp_s3_systematics_modelling.tex",
        "Generator-modelling and ISR/FSR scale uncertainties on background "
        "rejection at $50\\%$ signal efficiency, in the same fourteen bins, "
        "with the total of all four categories. All columns are relative "
        "uncertainties in percent.",
        "tab:supp-syst-modelling",
        "rr rrr rrrr r r",
        [r"$\pt$ low", r"$\pt$ high",
         "Signal model", "Bkg model", "Model total",
         "Signal ISR", "Signal FSR", "Bkg ISR", "Bkg FSR", "ISR/FSR total",
         "Total"],
        mod,
        note=r"$\pt$ bin edges in GeV. Signal modelling is measured only in the "
             r"bins below $1.5$~TeV and held at its maximum measured value from "
             r"$1.55$~TeV upwards; the $1350$--$1550$~GeV interval carries the "
             r"official plotting convention described in Section~4.1 of the "
             r"main text and is not an independent measurement of that "
             r"interval. The Total column is the quadrature sum of the cluster "
             r"and track totals of Table~\ref{tab:supp-syst-detector} with the "
             r"model and ISR/FSR totals here.",
        landscape=True, star=False, size="footnotesize", tabcolsep="4pt")

    # the two bin-edge columns are deliberately repeated in both tables
    want = tokens("\n".join(" & ".join(r) for r in rows))
    want += tokens("\n".join(" & ".join(r[:2]) for r in rows))
    got = tokens("\n".join(" & ".join(r) for r in det + mod))
    assert want == got, (want - got, got - want)
    print("S2/S3  14 bins split, every numeric token preserved")


# ---------------------------------------------------------------- conformal --
def conformal() -> None:
    src = HERE / "supplementary_conformal_round1.tex"
    rows = body_rows(src)
    assert len(rows) == 10 and all(len(r) == 20 for r in rows)

    # 0 dataset 1 n 2 n_s 3 n_b 4 cov 5 sig cov 6 bkg cov 7 d target
    # 8 d_s target 9 d_b target 10 mean size 11 singleton rate
    # 12 ambiguous rate 13 empty rate 14 singleton n 15 ambiguous n
    # 16 empty n 17 d nominal 18 d_s nominal 19 d_b nominal
    cov = [[r[0], r[1], r[2], r[3], r[5], r[6], r[4], r[8], r[9], r[7],
            r[18], r[19], r[17]] for r in rows]
    setstruct = [[r[0], r[10], r[11], r[12], r[13], r[14], r[15], r[16]]
                 for r in rows]

    emit(HERE / "supp_s4_conformal_coverage.tex",
         "Class-conditional split-conformal coverage at target $0.9$. The two "
         "class-conditional coverages are the primary quantities; the overall "
         "coverage is a descriptive number whose value depends on the class "
         "mixture of the sample, which differs strongly between the "
         "calorimeter and the track samples.",
         "tab:supp-conformal-coverage",
         "l rrr rrr rrr rrr",
         ["Dataset", "$n$", "$n_s$", "$n_b$",
          "Signal cov.", "Bkg cov.", "Overall cov.",
          r"$\Delta_s$ target", r"$\Delta_b$ target", r"$\Delta$ target",
          r"$\Delta_s$ nominal", r"$\Delta_b$ nominal", r"$\Delta$ nominal"],
         cov, landscape=True, star=False, size="footnotesize", tabcolsep="3pt",
         note=r"Deviations are quoted as fractions, from the $0.9$ target and "
              r"from the value measured on \texttt{test\_nominal}. Thresholds "
              r"were calibrated once on the frozen nominal validation split "
              r"and applied unchanged to every row.")

    emit(HERE / "supp_s5_conformal_sets.tex",
         "Structure of the class-conditional conformal prediction sets on the "
         "same samples: mean set size, and the rate and count of one-class, "
         "two-class and empty sets.",
         "tab:supp-conformal-sets",
         "l r rrr rrr",
         ["Dataset", "Mean set size",
          "Singleton rate", "Ambiguous rate", "Empty rate",
          "Singleton $n$", "Ambiguous $n$", "Empty $n$"],
         setstruct, star=False, size="footnotesize", tabcolsep="4pt",
         note=r"``Ambiguous'' denotes a prediction set containing both classes. "
              r"No sample produces an empty set.")

    want = tokens("\n".join(" & ".join(r) for r in rows))
    got = tokens("\n".join(" & ".join(r) for r in cov + setstruct))
    assert want == got, (want - got, got - want)
    print("S4/S5  conformal split, every numeric token preserved")


# -------------------------------------------------------------------- SHAP --
FEATURE_TEX = {
    "fjet_Tau1_wta": r"$\tau_1^{\mathrm{WTA}}$",
    "fjet_Tau2_wta": r"$\tau_2^{\mathrm{WTA}}$",
    "fjet_Tau3_wta": r"$\tau_3^{\mathrm{WTA}}$",
    "fjet_Tau4_wta": r"$\tau_4^{\mathrm{WTA}}$",
    "fjet_Split12": r"$\sqrt{d_{12}}$",
    "fjet_Split23": r"$\sqrt{d_{23}}$",
    "fjet_ECF1": r"ECF$_1$", "fjet_ECF2": r"ECF$_2$", "fjet_ECF3": r"ECF$_3$",
    "fjet_C2": r"$C_2$", "fjet_D2": r"$D_2$", "fjet_L2": r"$L_2$",
    "fjet_L3": r"$L_3$", "fjet_Qw": r"$Q_w$",
    "fjet_ThrustMaj": "ThrustMaj",
}
SYS_ORDER = ("esup", "esdown", "cpos", "cer")
SUBSET_ORDER = ("all", "signal", "background")
SIZE_ORDER = ("25000", "50000", "100000")


def g(value: str) -> str:
    """Six significant digits, LaTeX-safe, matching the frozen table style."""
    return f"{float(value):.6g}"


def shap() -> None:
    rows = list(csv.DictReader((DATA / "shap_delta_per_feature.csv").open(
        encoding="utf-8")))
    assert len(rows) == 540, len(rows)

    def key(r):
        return (SYS_ORDER.index(r["systematic"]),
                SIZE_ORDER.index(r["sample_size"]),
                SUBSET_ORDER.index(r["subset"]),
                list(FEATURE_TEX).index(r["feature"]))

    rows.sort(key=key)

    per_feature = [
        [r["systematic"].replace("_", r"\_"), r["sample_size"], r["subset"],
         FEATURE_TEX[r["feature"]], r["n_pairs"],
         g(r["mean_signed_delta_shap"]), g(r["median_signed_delta_shap"]),
         g(r["mean_abs_delta_shap"]), g(r["median_abs_delta_shap"]),
         g(r["nominal_mean_abs_shap"]), g(r["systematic_mean_abs_shap"]),
         g(r["relative_attribution_drift"]),
         r["nominal_importance_rank"], r["systematic_importance_rank"]]
        for r in rows]

    lines = ["% Generated by tables/make_supplementary_tables.py from the frozen",
             "% shap_delta_per_feature.csv of round 3. Values copied verbatim.",
             r"% Requires \usepackage{booktabs,longtable,pdflscape}.",
             r"\begin{landscape}", r"\scriptsize",
             r"\setlength{\tabcolsep}{1.6pt}",
             r"\begin{longtable}{llll r rrrr rr r rr}",
             r"\caption{Complete per-feature paired SHAP-Delta results, round 3. "
             r"SHAP values are exact TreeSHAP attributions of the frozen model "
             r"in the additive margin space of the booster. Mean "
             r"$|\Delta$SHAP$|$ is the mean over jets of the absolute per-jet "
             r"change in a feature's attribution; relative attribution drift is "
             r"the relative change in that feature's global mean $|$SHAP$|$. "
             r"The two are different quantities and are not interchangeable. "
             r"Score-level and rank-level summaries, which are properties of a "
             r"whole systematic--subset--sample-size group rather than of a "
             r"feature, are given separately in "
             r"Table~\ref{tab:supp-shap-scores}.}",
             r"\label{tab:supp-shap-per-feature}\\",
             r"\toprule"]
    header = ("Systematic & Size & Subset & Feature & $n$ & "
              r"Mean $\Delta$SHAP & Median $\Delta$SHAP & "
              r"Mean $|\Delta$SHAP$|$ & Median $|\Delta$SHAP$|$ & "
              r"Nom. mean $|$SHAP$|$ & Sys. mean $|$SHAP$|$ & "
              r"Rel. attr. drift & Nom. rank & Sys. rank \\")
    lines += [header, r"\midrule", r"\endfirsthead",
              r"\toprule", header, r"\midrule", r"\endhead",
              r"\bottomrule", r"\endfoot"]
    lines += [" & ".join(r) + r" \\" for r in per_feature]
    lines += [r"\end{longtable}", r"\end{landscape}"]
    (HERE / "supp_s6_shap_per_feature.tex").write_text(
        "\n".join(lines) + "\n", encoding="utf-8")

    # one row per (systematic, sample size, subset): the score and rank
    # summaries, which the frozen twenty-column table repeated on all fifteen
    # feature rows of each group.
    seen: dict[tuple[str, str, str], dict[str, str]] = {}
    for r in rows:
        k = (r["systematic"], r["sample_size"], r["subset"])
        if k in seen:
            for f in ("mean_signed_delta_score", "median_signed_delta_score",
                      "mean_abs_delta_score", "global_importance_spearman_rho",
                      "n_pairs"):
                assert seen[k][f] == r[f], (k, f)
        else:
            seen[k] = r
    assert len(seen) == 36, len(seen)

    scores = [[k[0].replace("_", r"\_"), k[1], k[2], v["n_pairs"],
               g(v["mean_signed_delta_score"]),
               g(v["median_signed_delta_score"]),
               g(v["mean_abs_delta_score"]),
               g(v["global_importance_spearman_rho"])]
              for k, v in sorted(seen.items(), key=lambda kv: (
                  SYS_ORDER.index(kv[0][0]), SIZE_ORDER.index(kv[0][1]),
                  SUBSET_ORDER.index(kv[0][2])))]

    emit(HERE / "supp_s7_shap_scores.tex",
         "Score-level and rank-level summaries of the paired SHAP-Delta "
         "campaign. Each row is one systematic, sample size and class subset. "
         "Score changes are in probability space. $\\rho$ is the Spearman "
         "correlation between the nominal and varied global feature-importance "
         "orderings within that subset; its minimum over all twelve "
         "systematic--subset combinations at $100{,}000$ pairs is $0.986$, and "
         "over the four all-jet combinations $0.993$.",
         "tab:supp-shap-scores",
         "l r l r rrr r",
         ["Systematic", "Size", "Subset", "$n$",
          r"Mean $\Delta$score", r"Median $\Delta$score",
          r"Mean $|\Delta$score$|$", r"$\rho$"],
         scores, star=False)

    # Independent cross-check against the frozen twenty-column table: for every
    # (subset, feature, systematic, sample size) key, the values this script
    # emits must be character-identical to the frozen ones.
    frozen = [r for r in body_rows(
        HERE / "supplementary_shap_delta_round3_all_features.tex")
        if r[0] in SUBSET_ORDER]
    assert len(frozen) == 540, len(frozen)
    # frozen columns: 0 subset 1 feature 2 n 3 meanD 4 medD 5 meanAbsD
    # 6 medAbsD 7 nomAbs 8 sysAbs 9 relDrift 10 defined 11 nomRank
    # 12 sysRank 13 rho 14 p 15 systematic 16 size 17 meanDs 18 medDs
    # 19 meanAbsDs
    fz = {(r[0], r[1].replace(r"\_", "_"), r[15].replace(r"\_", "_"), r[16]): r
          for r in frozen}
    assert len(fz) == 540
    for src, out in zip(rows, per_feature):
        f = fz[(src["subset"], src["feature"],
                src["systematic"], src["sample_size"])]
        assert out[4:12] == [f[2], f[3], f[4], f[5], f[6], f[7], f[8], f[9]], \
            (out, f)
        assert out[12:14] == [f[11], f[12]], (out, f)
    for row in scores:
        sysname = row[0].replace(r"\_", "_")
        match = [f for k, f in fz.items()
                 if k[2] == sysname and k[3] == row[1] and k[0] == row[2]]
        assert len(match) == 15
        for f in match:
            assert [f[17], f[18], f[19], f[13]] == row[4:8], (row, f)
    print("S6/S7  SHAP split into 540 per-feature rows and 36 summary rows; "
          "every value cross-checked against the frozen twenty-column table")


if __name__ == "__main__":
    systematics()
    conformal()
    shap()
